"use client";

import { FormEvent, useCallback, useEffect, useState } from "react";
import { AdminShell } from "@/components/admin/AdminShell";
import { createSupabaseBrowserClient } from "@/lib/db/browser";

type Enrollment = { factorId: string; qrCode: string; secret: string };

/**
 * Authenticator-app (TOTP) enrollment and step-up for staff.
 * PRC exports require an aal2 session, so staff enroll here and enter a
 * code at sign-in. Nothing here weakens any existing check.
 */
export function MfaPanel() {
  const [loading, setLoading] = useState(true);
  const [verifiedFactorId, setVerifiedFactorId] = useState<string | null>(null);
  const [assurance, setAssurance] = useState<string>("aal1");
  const [enrollment, setEnrollment] = useState<Enrollment | null>(null);
  const [code, setCode] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");

  const refresh = useCallback(async () => {
    const supabase = createSupabaseBrowserClient();
    const [{ data: factors }, { data: level }] = await Promise.all([
      supabase.auth.mfa.listFactors(),
      supabase.auth.mfa.getAuthenticatorAssuranceLevel(),
    ]);
    const verified = factors?.totp?.find((factor) => factor.status === "verified");
    setVerifiedFactorId(verified?.id ?? null);
    setAssurance(level?.currentLevel ?? "aal1");
    setLoading(false);
  }, []);

  useEffect(() => {
    // Initial load of the factor list from Supabase Auth.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    void refresh();
  }, [refresh]);

  async function startEnrollment() {
    setError(""); setNotice(""); setBusy(true);
    try {
      const supabase = createSupabaseBrowserClient();
      const { data, error: enrollError } = await supabase.auth.mfa.enroll({ factorType: "totp", friendlyName: `SafeCard admin ${new Date().toISOString().slice(0, 10)}` });
      if (enrollError || !data) throw enrollError ?? new Error("Could not start enrollment.");
      setEnrollment({ factorId: data.id, qrCode: data.totp.qr_code, secret: data.totp.secret });
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "Could not start enrollment.");
    } finally { setBusy(false); }
  }

  async function verify(event: FormEvent) {
    event.preventDefault();
    const factorId = enrollment?.factorId ?? verifiedFactorId;
    if (!factorId) return;
    setError(""); setNotice(""); setBusy(true);
    try {
      const supabase = createSupabaseBrowserClient();
      const { error: verifyError } = await supabase.auth.mfa.challengeAndVerify({ factorId, code: code.trim() });
      if (verifyError) throw verifyError;
      setEnrollment(null); setCode("");
      setNotice("Authenticator verified. This session is now at the higher assurance level required for exports.");
      await refresh();
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "That code was not accepted. Check the code and try again.");
    } finally { setBusy(false); }
  }

  return <AdminShell>
    <p className="eyebrow">Account security</p>
    <h1>Authenticator app (MFA)</h1>
    <p>PRC exports contain personal data, so they require a second step. Use any authenticator app (Google Authenticator, Authy, 1Password, Microsoft Authenticator).</p>
    {loading && <p>Loading…</p>}
    {!loading && !verifiedFactorId && !enrollment && <>
      <div className="notice-panel amber"><strong>Not set up</strong><span>Your account has no authenticator yet, so exports are blocked.</span></div>
      <button className="button-primary" type="button" disabled={busy} onClick={startEnrollment}>{busy ? "Starting…" : "Set up authenticator app"}</button>
    </>}
    {!loading && enrollment && <form className="portal-form" onSubmit={verify}>
      <p><strong>1.</strong> Scan this QR code with your authenticator app.</p>
      {/* qr_code is an SVG data URL generated by Supabase Auth */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={enrollment.qrCode} alt="Authenticator QR code" width={200} height={200} />
      <p>Cannot scan? Enter this key manually: <code>{enrollment.secret}</code></p>
      <label><span><strong>2.</strong> Enter the 6-digit code it shows</span><input inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" maxLength={6} value={code} onChange={(event) => setCode(event.target.value)} required /></label>
      {error && <p className="form-message error">{error}</p>}
      <button className="button-primary" disabled={busy}>{busy ? "Verifying…" : "Verify and turn on"}</button>
    </form>}
    {!loading && verifiedFactorId && !enrollment && <>
      <div className="notice-panel"><strong>Authenticator is set up</strong><span>Current session level: {assurance === "aal2" ? "verified (aal2), exports allowed" : "password only (aal1), exports blocked until you enter a code"}.</span></div>
      {assurance !== "aal2" && <form className="portal-form" onSubmit={verify}>
        <label><span>Enter the 6-digit code from your authenticator</span><input inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" maxLength={6} value={code} onChange={(event) => setCode(event.target.value)} required /></label>
        {error && <p className="form-message error">{error}</p>}
        <button className="button-primary" disabled={busy}>{busy ? "Verifying…" : "Verify code"}</button>
      </form>}
    </>}
    {notice && <p className="form-message" role="status">{notice}</p>}
    {!enrollment && error && verifiedFactorId && assurance === "aal2" && <p className="form-message error">{error}</p>}
  </AdminShell>;
}
